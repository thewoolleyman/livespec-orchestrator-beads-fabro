"""The materialized carry-forward decision program, assembled from its fragments.

`SPECIFICATION/contracts.md` section "Definition-of-Done and Proof-of-Done
stages" -> "The decision" (v138) puts the carry-forward decision inside a
changed-head `pr_refresh`, before routing. The engine gives a command node two
outcomes, so the decision IS its exit code: zero routes `pr_refresh_head` to
`pr`, non-zero routes it to `proof_capture`.

WHY A MATERIALIZED PROGRAM RATHER THAN SHELL IN THE NODE. The decision reads a
Proof of Done record, grades every reproduction step against a closed command
grammar, canonicalizes each path operand, takes two patch identities, a blob
identity per observed path and a raw identity per working-tree read, and then
EXECUTES each step. None of that is expressible in a node `script`, and the half
that is -- the record read -- is the half `_dispatcher_publication_head` measured
a hand-rolled shell reader getting wrong on 100% of real records.

WHY IT IS ASSEMBLED FROM FOUR FRAGMENTS RATHER THAN WRITTEN AS ONE STRING. Each
fragment is owned by the module that owns its concern: the grammar closure, the
record format, the decision rule, and this assembly. That is the same
cohesion split the rest of this tree uses, and it is what lets the grammar's own
test exercise the grammar alone while this module's test exercises the whole
program. The ORDER is load-bearing and is not alphabetical: the record reader
defines `FENCE` and `fence_after`, the grammar defines `canonical_path` and the
three `*_COMMAND` reasons, the record parse uses all five, and the decision uses
everything -- so a reordering produces a `NameError` at import rather than a
wrong answer, which is the direction a composition error should fail in.

WHY THE PROGRAM IS STDLIB-ONLY AND CARRIES NO LIVESPEC IMPORT. The sandbox clone
is the GOVERNED repository and has no copy of this package, exactly as the
plugin-cache gate and the publication-head reader record. The `import` lines the
fragments need are hoisted here, once, because a fragment carrying its own
imports would re-import `re` three times and -- worse -- would let one fragment
be read as runnable on its own when it is not.
"""

from __future__ import annotations

import json

from livespec_orchestrator_beads_fabro.commands._dispatcher_carry_forward_decision import (
    decision_fragment,
)
from livespec_orchestrator_beads_fabro.commands._dispatcher_carry_forward_grammar import (
    grammar_program_fragment,
)
from livespec_orchestrator_beads_fabro.commands._dispatcher_carry_forward_record import (
    record_parse_fragment,
    record_reader_fragment,
)
from livespec_orchestrator_beads_fabro.commands._dispatcher_sandbox_plugins import (
    sandbox_plugins_root_expansion,
)

__all__: list[str] = [
    "CARRY_FORWARD_PROGRAM_FILENAME",
    "carry_forward_program_path_expansion",
    "carry_forward_program_prepare_steps_block",
    "carry_forward_program_source",
]

# The program's filename below the sandbox plugins root.
#
# Fail-closed is the node's own existence check rather than a `${VAR:?}` guard,
# for the reason the publication-head program gives: a sandbox the prepare step
# did not reach carries no program, and a refresh that carried a proof forward
# without deciding anything is the one outcome that must not be reachable.
CARRY_FORWARD_PROGRAM_FILENAME = "livespec-carry-forward-decision.py"

# The one import block the four fragments share. `time` is here rather than in
# the decision fragment because the record's header timestamp is the only use of
# it, and hoisting every import makes the composition order the ONLY thing the
# assembly decides.
_PROGRAM_PREAMBLE = '''"""The carry-forward decision, materialized by the Dispatcher.

Assembled from `_dispatcher_carry_forward_record`,
`_dispatcher_carry_forward_grammar`, their parse, and
`_dispatcher_carry_forward_decision`. Do not edit this file in a sandbox: it is
rewritten from those modules on every dispatch.
"""

import time
'''


def carry_forward_program_source() -> str:
    """The materialized program's exact bytes, in the one admissible order.

    The composition is the whole of this function, and the sequence is the
    dependency order the module docstring records. A test that materialized the
    fragments in any other order would fail at import, which is why no test
    asserts the order as a string comparison.
    """
    return (
        _PROGRAM_PREAMBLE
        + record_reader_fragment()
        + grammar_program_fragment()
        + record_parse_fragment()
        + decision_fragment()
    )


def carry_forward_program_path_expansion() -> str:
    """The shell expansion `pr_refresh_head` resolves the program through.

    PUBLIC and spelled once, for the reason the publication-head program's own
    expansion records: a node resolving a DIFFERENT root than the prepare pass
    would find no program at all, and the failure would then read as a
    Dispatcher that never materialized one.
    """
    return f"{sandbox_plugins_root_expansion()}/{CARRY_FORWARD_PROGRAM_FILENAME}"


def carry_forward_program_prepare_steps_block() -> str:
    """The prepare step that lands the program below the sandbox plugins root.

    Written through a heredoc with a QUOTED delimiter, so the shell expands
    nothing inside the program: the decision carries dollar-bearing,
    shell-looking text of its own -- the forbidden-character set alone contains
    `$` and a backtick -- and an unquoted heredoc would substitute into it.
    """
    root = sandbox_plugins_root_expansion()
    script = (
        f'set -eu\nmkdir -p "{root}"\n'
        f'cat > "{root}/{CARRY_FORWARD_PROGRAM_FILENAME}" '
        f"<<'LIVESPEC_CARRY_FORWARD_PROGRAM'\n"
        f"{carry_forward_program_source()}"
        "LIVESPEC_CARRY_FORWARD_PROGRAM"
    )
    return (
        "\n# --- Dispatcher-materialized carry-forward decision program: the\n"
        "# --- deterministic rule a changed-head pr_refresh decides by, with no\n"
        "# --- language-model judgement in it (bd-ib-v4exlm) ---\n"
        "[[run.prepare.steps]]\n"
        f"script = {json.dumps(script)}\n"
    )
